"""Acceptance tests for the HTML report — specs/17-html-report.md.

The per-kind summary tests build ``Change`` objects directly and call
:func:`render_change_summary` so each template is pinned in isolation. The
``test_render_golden_*`` tests assert byte-for-byte equality against
``tests/fixtures/html/*.html`` (generated by the renderer, then hand-reviewed);
the timestamp is pinned via ``SOURCE_DATE_EPOCH`` so the goldens are stable.
"""

from __future__ import annotations

import dataclasses
import re
