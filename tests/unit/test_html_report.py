from owlcompare.report.html_report import HtmlOptions, render

FIXTURES = Path(__file__).resolve().parent.parent / "fixtures"
DIFF = FIXTURES / "diff"
RENAME = FIXTURES / "rename"
ANON = FIXTURES / "anonstruct"
GOLDEN = FIXTURES / "html"

_ERA = {"era": "http://data.europa.eu/949/"}


@pytest.fixture(autouse=True)
def _pin_timestamp(monkeypatch: pytest.MonkeyPatch) -> None:
    """Pin SOURCE_DATE_EPOCH so every render in this module is deterministic."""
    monkeypatch.setenv("SOURCE_DATE_EPOCH", "0")


# --------------------------------------------------------------------------- #
# Result / change builders
# --------------------------------------------------------------------------- #


def _result(name_a: str, name_b: str, base: Path = DIFF, **run_kwargs: object) -> DiffResult:
    a = dataclasses.replace(load(str(base / name_a)), source=name_a)
    b = dataclasses.replace(load(str(base / name_b)), source=name_b)
    return orchestrator.run(a, b, **run_kwargs)  # type: ignore[arg-type]


def _render(name_a: str, name_b: str, base: Path = DIFF, **run_kwargs: object) -> str:
    return render(_result(name_a, name_b, base, **run_kwargs))


def _change(kind: str, severity: str = "additive", summary: str = "", **details: object) -> Change:
    return Change(
        layer="structural",
        kind=kind,
        severity=severity,  # type: ignore[arg-type]
        subject=str(details.get("entity_iri") or details.get("before_iri") or ""),
        summary=summary,
        details=details,
    )


def _synthetic_result(count: int) -> DiffResult:
    """A DiffResult with ``count`` additive class_added changes (size/large tests)."""
    snapshot = dataclasses.replace(load(str(DIFF / "html_escaping_before.ttl")), source="a.ttl")
    snapshot_b = dataclasses.replace(snapshot, source="b.ttl")
    changes = tuple(
        Change(
            layer="structural",
            kind="class_added",
            severity="additive",
            subject=f"http://example.org/C{i:05d}",
            summary=f"Class added: ex:C{i:05d}",
            details={
                "entity_iri": f"http://example.org/C{i:05d}",
                "entity_kind": "class",
                "label": f"Class {i:05d}",
                "language": "en",
                "change_id": f"structural:class_added:{i:05d}",
            },
        )
        for i in range(count)
    )
    return DiffResult(a=snapshot, b=snapshot_b, changes=changes, metadata={})


