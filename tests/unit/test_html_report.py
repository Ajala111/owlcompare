def _result_anon(name_a: str, name_b: str) -> DiffResult:
    a = dataclasses.replace(load(str(ANON / name_a)), source="era_axleSpacingDistance_v1.ttl")
    b = dataclasses.replace(load(str(ANON / name_b)), source="era_axleSpacingDistance_v2.ttl")
    return orchestrator.run(a, b)


def _section(html: str, anchor: str) -> str:
    start = html.index(f'id="section-{anchor}"')
    section_start = html.rindex("<section", 0, start)
    end = html.index("</section>", start)
    return html[section_start:end]


def _card(html: str, kind: str) -> str:
    match = re.search(
        rf'<article class="change-card[^>]*data-kind="{kind}".*?</article>', html, re.S
    )
    assert match, f"no card for kind {kind}"
    return match.group(0)
