def test_render_system_out_escapes_cdata_terminator():
    # A label smuggling a "]]>" must not terminate the CDATA section early.
    change = _change(
        "class_added",
        severity="additive",
        summary="Class added: evil ]]> escape attempt",
        entity_iri="http://example.org/Evil",
    )
    out = render(_synthetic_result((change,)))
    # The split-CDATA escape is applied (the lone "]]>" within it is the legitimate
    # terminator of the first chunk; a fresh CDATA reopens for the trailing ">")...
    assert "]]]]><![CDATA[>" in out
    # ...and the document still parses, recovering the original three characters.
    text = ET.fromstring(out).find(".//system-out").text
    assert "evil ]]> escape attempt" in text


