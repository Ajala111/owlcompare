def test_render_failure_body_includes_iri_and_details():
    change = _change(
        "class_removed",
        severity="breaking",
        summary="Class removed",
        entity_iri="http://example.org/Cat",
        label="Cat",
        language="en",
    )
    out = render(_synthetic_result((change,)))
    root = ET.fromstring(out)
    body = root.find(".//failure").text
    assert "Entity:    http://example.org/Cat" in body  # the full IRI, not the prefixed form
    assert "Kind:      class_removed" in body
    assert '"Cat"@en' in body
    assert "Severity:  breaking" in body


