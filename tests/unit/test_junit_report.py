def test_render_xml_escapes_special_chars_in_labels():
    change = _change(
        "class_removed",
        severity="breaking",
        summary="Class removed",
        entity_iri="http://example.org/X",
        label="<script>alert('x')</script>",
        language="en",
    )
    out = render(_synthetic_result((change,)))
    # The failure body is element text: < and > become entities, no live tag.
    assert "&lt;script&gt;" in out
    assert "<script>alert" not in out


def test_render_xml_escapes_quotes_in_attributes():
    change = _change(
        "class_removed",
        severity="breaking",
        summary='Class removed: "Quoted" name',
        entity_iri="http://example.org/X",
    )
    out = render(_synthetic_result((change,)))
    # The summary is the failure message attribute; its quotes must be escaped.
    assert 'message="Class removed: &quot;Quoted&quot; name"' in out


def test_render_xml_escapes_ampersand_in_iris():
    change = _change(
        "class_removed",
        severity="breaking",
        summary="Class removed",
        entity_iri="http://example.org/A&B",
    )
    out = render(_synthetic_result((change,)))
    body = ET.fromstring(out).find(".//failure").text  # parses only if & is escaped
    assert "http://example.org/A&B" in body


