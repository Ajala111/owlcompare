# --------------------------------------------------------------------------- #
# Golden files (byte-for-byte locked contract; SOURCE_DATE_EPOCH pinned)
# --------------------------------------------------------------------------- #


def _golden(name: str) -> str:
    return (GOLDEN / name).read_text(encoding="utf-8")


def test_render_golden_empty():
    out = render(_result("identical_a.ttl", "identical_b.ttl"))
    assert out == _golden("empty.xml")


