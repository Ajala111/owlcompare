"""Acceptance tests for the JUnit XML report — specs/18-junit-xml.md.

The fine-grained tests build ``Change`` objects directly so each mapping rule and
escaping path is pinned in isolation; the ``test_render_golden_*`` tests assert
byte-for-byte equality against ``tests/fixtures/junit/*.xml`` (generated by the
renderer, then hand-reviewed). ``SOURCE_DATE_EPOCH`` is pinned module-wide so the
``timestamp`` attribute is stable.
"""

from __future__ import annotations

import dataclasses
import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

from owlcompare.diff import orchestrator
from owlcompare.diff._common import Change, DiffResult
from owlcompare.loader import load
from owlcompare.report.junit_report import JUnitOptions, render

FIXTURES = Path(__file__).resolve().parent.parent / "fixtures"
DIFF = FIXTURES / "diff"
RENAME = FIXTURES / "rename"
GOLDEN = FIXTURES / "junit"

_ERA = {"era": "http://data.europa.eu/949/"}


@pytest.fixture(autouse=True)
def _pin_timestamp(monkeypatch: pytest.MonkeyPatch) -> None:
    """Pin SOURCE_DATE_EPOCH so every render in this module is deterministic."""
    monkeypatch.setenv("SOURCE_DATE_EPOCH", "0")


# --------------------------------------------------------------------------- #
# Result / change builders
# --------------------------------------------------------------------------- #


def _result(name_a: str, name_b: str, base: Path = DIFF, **run_kwargs: object) -> DiffResult:
    a = dataclasses.replace(load(str(base / name_a)), source=name_a)
    b = dataclasses.replace(load(str(base / name_b)), source=name_b)
    return orchestrator.run(a, b, **run_kwargs)  # type: ignore[arg-type]


def _change(kind: str, severity: str = "additive", summary: str = "", **details: object) -> Change:
    return Change(
        layer="structural",
        kind=kind,
        severity=severity,  # type: ignore[arg-type]
        subject=str(details.get("entity_iri") or details.get("before_iri") or "") or None,
        summary=summary,
        details=details,
    )


def _synthetic_result(changes: tuple[Change, ...]) -> DiffResult:
    """A DiffResult with hand-built changes and no orchestrator metadata."""
    snapshot = dataclasses.replace(load(str(DIFF / "identical_a.ttl")), source="a.ttl")
    snapshot_b = dataclasses.replace(snapshot, source="b.ttl")
    return DiffResult(a=snapshot, b=snapshot_b, changes=changes, metadata={})


